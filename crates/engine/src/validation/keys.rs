//! Durable submission identities: `<unix-milliseconds>:<uuid-v4>` (contract §9.2).

use std::collections::hash_map::RandomState;
use std::hash::{BuildHasher, Hasher};
use std::time::{SystemTime, UNIX_EPOCH};

use super::{ValidationError, ids};

/// How far ahead a submission timestamp may be.
pub const MAX_FUTURE_MS: u64 = 5 * 60 * 1000;
/// How old a submission key may be.
pub const MAX_AGE_MS: u64 = 7 * 24 * 60 * 60 * 1000;

/// A validated durable submission key.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SubmissionKey {
    pub text: String,
    pub timestamp_ms: u64,
}

impl SubmissionKey {
    /// Validate `<unix-ms>:<uuid-v4>` and its freshness against `now_ms`.
    pub fn parse(text: &str, now_ms: u64) -> Result<Self, ValidationError> {
        if text.len() > 128 || text.is_empty() {
            return Err(ValidationError::invalid_request("SubmissionKey must be 1..=128 bytes"));
        }
        let (millis, uuid) = text.split_once(':').ok_or_else(|| ValidationError::invalid_request("SubmissionKey must be <unix-ms>:<uuid-v4>"))?;
        if millis.is_empty() || millis.len() > 20 || !millis.bytes().all(|b| b.is_ascii_digit()) {
            return Err(ValidationError::invalid_request("SubmissionKey timestamp must be unix milliseconds"));
        }
        let timestamp_ms: u64 = millis.parse().map_err(|_| ValidationError::invalid_request("SubmissionKey timestamp is not a u64"))?;
        if !valid_uuid_v4(uuid) {
            return Err(ValidationError::invalid_request("SubmissionKey UUID must be a lowercase UUID v4"));
        }
        if timestamp_ms > now_ms.saturating_add(MAX_FUTURE_MS) {
            return Err(ValidationError::invalid_request("SubmissionKey is more than five minutes in the future"));
        }
        if now_ms.saturating_sub(timestamp_ms) >= MAX_AGE_MS {
            return Err(ValidationError::request_expired("SubmissionKey is seven days old or older"));
        }
        Ok(SubmissionKey { text: text.into(), timestamp_ms })
    }

    pub fn expires_at_ms(&self) -> u64 {
        self.timestamp_ms.saturating_add(MAX_AGE_MS)
    }

    /// The key file's stable name: the SHA-256 of the exact key text.
    pub fn file_name(&self) -> String {
        solidcraft_io::candidate::digest_hex(self.text.as_bytes())
    }
}

/// A freshly generated durable key for `now_ms` (host-generated, never from model text).
pub fn generate(now_ms: u64) -> String {
    format!("{now_ms}:{}", uuid_v4())
}

/// UUID v4 text from the standard library's randomly seeded hasher plus the clock and process
/// identity. It is a host identity, never a credential.
pub fn uuid_v4() -> String {
    let nanos = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_nanos()).unwrap_or(0);
    let pid = u64::from(std::process::id());
    let first_state = RandomState::new();
    let second_state = RandomState::new();
    let mut first = first_state.build_hasher();
    first.write_u128(nanos);
    first.write_u64(pid);
    let mut second = second_state.build_hasher();
    second.write_u128(nanos.rotate_left(64));
    second.write_u64(pid);
    let mut bytes = [0_u8; 16];
    bytes[..8].copy_from_slice(&first.finish().to_be_bytes());
    bytes[8..].copy_from_slice(&second.finish().to_be_bytes());
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    let hex: String = bytes.iter().map(|byte| format!("{byte:02x}")).collect();
    format!("{}-{}-{}-{}-{}", &hex[0..8], &hex[8..12], &hex[12..16], &hex[16..20], &hex[20..32])
}

fn valid_uuid_v4(uuid: &str) -> bool {
    let bytes = uuid.as_bytes();
    bytes.len() == 36
        && bytes[8] == b'-'
        && bytes[13] == b'-'
        && bytes[18] == b'-'
        && bytes[23] == b'-'
        && bytes.iter().enumerate().all(|(index, byte)| {
            if matches!(index, 8 | 13 | 18 | 23) { *byte == b'-' } else { byte.is_ascii_digit() || (b'a'..=b'f').contains(byte) }
        })
        && bytes[14] == b'4'
        && matches!(bytes[19], b'8' | b'9' | b'a' | b'b')
}

/// A run identity generated by this host.
pub fn run_id(now_ms: u64) -> String {
    let mut hasher = RandomState::new().build_hasher();
    hasher.write_u128(now_ms as u128);
    hasher.write_u64(u64::from(std::process::id()));
    let suffix = uuid_v4().replace('-', "");
    format!("run-{}-{:016x}", &suffix[..16], hasher.finish())
}

/// Is `text` a valid run identity this host could have generated?
pub fn valid_run_id(text: &str) -> bool {
    ids::valid_id(text) && text.starts_with("run-")
}

#[cfg(test)]
mod tests {
    use super::*;

    const NOW: u64 = 1_760_000_000_000;

    #[test]
    fn generated_keys_are_valid_uuid_v4_and_round_trip() {
        let key = generate(NOW);
        let parsed = SubmissionKey::parse(&key, NOW).unwrap();
        assert_eq!(parsed.timestamp_ms, NOW);
        assert_eq!(parsed.text, key);
        let uuid = key.split_once(':').unwrap().1;
        assert_eq!(&uuid[14..15], "4");
        assert!(matches!(&uuid[19..20], "8" | "9" | "a" | "b"));
    }

    #[test]
    fn stale_future_and_malformed_keys_are_refused() {
        let uuid = uuid_v4();
        assert!(SubmissionKey::parse(&format!("{}:{uuid}", NOW - MAX_AGE_MS), NOW).is_err());
        assert!(SubmissionKey::parse(&format!("{}:{uuid}", NOW + MAX_FUTURE_MS + 1), NOW).is_err());
        assert!(SubmissionKey::parse(&format!("{NOW}:{uuid}extra"), NOW).is_err());
        assert!(SubmissionKey::parse(&format!("{NOW}:00000000-0000-1000-8000-000000000000"), NOW).is_err());
        assert!(SubmissionKey::parse(&format!("{NOW}:{uuid}"), NOW).is_ok());
    }

    #[test]
    fn run_ids_are_valid_ids() {
        let id = run_id(NOW);
        assert!(valid_run_id(&id));
        assert!(!valid_run_id("run-../bad"));
        assert!(!valid_run_id("cand-1"));
    }
}
